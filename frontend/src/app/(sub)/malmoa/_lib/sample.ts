import type { Meeting, Segment } from "./types";

// 변환 결과를 흉내 내기 위한 예시 원문. 백엔드가 붙으면 서버의 변환 결과로 바뀐다.
const SPEECH: [number, string][] = [
  [0, "안녕하세요, 이번 주 스프린트 회의 시작하겠습니다."],
  [12, "지난주에 로그인과 회원가입 화면은 끝났고, 관리자 화면은 아직 진행 중입니다."],
  [31, "관리자 화면은 멤버 목록까지 붙었고 권한 변경 대화상자가 남았습니다."],
  [52, "이번 주 목표는 녹음 기능과 회의록 화면을 완성하는 것입니다."],
  [75, "녹음은 10초마다 저장하고, 탭이 꺼져도 복구할 수 있게 하기로 했습니다."],
  [98, "회의록 형식은 여덟 가지 항목으로 고정하고, 담당자가 없으면 확인 필요로 남깁니다."],
  [124, "일정은 다음 주 금요일까지 데모를 목표로 하겠습니다."],
  [146, "API 키 발급은 누가 하죠? 아직 정해지지 않았습니다."],
  [165, "그 부분은 다음 회의에서 정하겠습니다. 오늘 회의 마치겠습니다."],
];

const BOARD: [string, number][] = [
  ["1. 로그인 · 회원가입 → 10월 말", 0.92],
  ["2. 관리자 화면 → 11월 첫째 주", 0.9],
  ["3. 말모아 기능 정의서 자동 생성", 0.88],
  ["API 키 발급 / 비용 확인!!", 0.81],
  ["미어캣 출시 일정", 0.31],
];

export const LOW_CONFIDENCE = 0.4;

export function transcriptFor(m: Pick<Meeting, "source">): Segment[] {
  if (m.source === "image") return BOARD.map(([text, confidence]) => ({ start: 0, end: 0, text, confidence }));
  return SPEECH.map(([start, text], i) => ({ start, end: SPEECH[i + 1]?.[0] ?? start + 10, text }));
}

export function minutesTemplate(title: string): string {
  const name = title.replace(/\.[^.]+$/, "");
  return `# ${name}

## 1. 회의 제목
${name} 스프린트 회의

## 2. 회의 개요
- 일시: 확인 필요
- 참석자: 확인 필요
- 목적: 이번 주 진행 상황 공유와 다음 목표 합의

## 3. 주요 논의 내용
- 로그인·회원가입 화면은 완료, 관리자 화면은 멤버 목록까지 구현되었고 권한 변경 대화상자가 남음
- 녹음은 10초마다 저장하고, 탭이 꺼져도 복구할 수 있게 구현
- 회의록은 8개 항목으로 고정하고, 담당자가 없으면 '확인 필요'로 표시

## 4. 핵심 요약
이번 주는 녹음 기능과 회의록 화면 완성이 목표이며, 다음 주 금요일까지 데모를 준비한다.

## 5. 결정 사항
- 회의록 형식을 8개 항목으로 고정한다.
- 녹음 조각은 10초마다 저장한다.

## 6. 담당자별 실행 과제
- 녹음 기능 구현: 확인 필요
- 회의록 화면 완성: 확인 필요
- API 키 발급: 확인 필요 (담당자 미정)

## 7. 일정 및 마감일
- 데모: 다음 주 금요일

## 8. 추가 확인이 필요한 사항
- API 키 발급 담당자와 비용 확인 → 다음 회의에서 결정
- 회의 일시와 참석자 → **확인 필요**
`;
}
